"""Measure over-claiming, cold start, and the no-history positions.

This catalogue has no watch labels, so there is no accuracy, no train/test
loss, and no classical overfit curve. The numbers here are the stand-ins:

- saturation: share of top-10 neighbours with cosine >= the configured
  ceiling. A high share means the model has collapsed onto genre tokens.
- people-backed: share of top-10 neighbours that share a director or a
  billed actor. That is the non-circular signal.
- cold-start probes: fixed sentences with no user history, including
  empty, stop-words, out-of-vocabulary, genre words, a director name,
  and mood words that are not in the catalogue.

Writes ``reports/reliability.md``. Re-run the script to refresh it.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

_ROOT = Path(__file__).resolve().parents[1]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from src.config import load_config  # noqa: E402
from src.logging_conf import configure_logging  # noqa: E402
from src.models.persistence import load_recommender  # noqa: E402
from src.models.recommender import EmptyQueryError, TitleNotFoundError  # noqa: E402

PROBES: list[tuple[str, str]] = [
    ("empty", ""),
    ("stop words only", "the and of a"),
    ("out of vocabulary", "qqqq zzzz yyyy"),
    ("genre words", "crime drama thriller"),
    ("kids genre words", "kids family comedy"),
    ("stand-up words", "stand-up comedy"),
    ("director name", "Martin Scorsese"),
    ("mood words absent from genres", "slow burn melancholy"),
    ("a real title typed as taste", "breaking bad"),
    ("single token", "drama"),
]


def main() -> None:
    configure_logging()
    config = load_config()
    model = load_recommender(config.models_dir, config)
    rng = np.random.default_rng(config.random_seed)
    n_items = len(model.titles)
    sample = rng.choice(n_items, size=min(400, n_items), replace=False)
    ceiling = config.recommender.saturated_similarity
    saturated = 0
    people = 0
    considered = 0
    for index in sample:
        _resolved, results = model.recommend(
            str(model.show_ids[int(index)]), n=10, exclude_same_franchise=True
        )
        for item in results:
            considered += 1
            if item.similarity >= ceiling:
                saturated += 1
            if item.shared_people:
                people += 1
    sat_rate = saturated / considered if considered else float("nan")
    people_rate = people / considered if considered else float("nan")

    probe_rows: list[str] = []
    for name, query in PROBES:
        try:
            results = model.recommend_from_text(query, n=3)
        except EmptyQueryError as exc:
            probe_rows.append(f"| {name} | `{query or '(empty)'}` | refused | {exc} |")
            continue
        top = results[0]
        genres = ", ".join(top.shared_genres) or "—"
        probe_rows.append(
            f"| {name} | `{query}` | {top.title} ({top.similarity:.3f}) | {genres}. {top.reason} |"
        )

    fuzzy_rows: list[str] = []
    for typed in ("breakng bad", "strager things", "the irishmn", "zzzznotitle"):
        try:
            resolved, results = model.recommend(typed, n=1)
        except TitleNotFoundError as exc:
            fuzzy_rows.append(f"| `{typed}` | no match | {exc.suggestions[:3]} |")
            continue
        fuzzy_rows.append(
            f"| `{typed}` | {resolved.title} (from {resolved.resolved_from}) | {results[0].title} |"
        )

    lines = [
        "# Reliability",
        "",
        "Generated by `scripts/reliability.py` from the artifacts in `models/`.",
        "Re-run the script to refresh every number.",
        "",
        "## What was not computed",
        "",
        "Accuracy was not computed. There are no likes, watches, or ratings to be",
        "correct about. A train/test loss was not computed, so classical overfitting",
        "and underfitting curves do not exist for this model. The vectoriser can",
        "still collapse onto a feature. That is what the saturation number measures.",
        "The model does not generate prose from a language model. The failure mode",
        "that looks like a hallucination is a reason or a score that claims more",
        "than the overlapping tokens support.",
        "",
        "## Saturation on catalogue titles",
        "",
        f"Sample of {len(sample)} titles, seed {config.random_seed}, top 10,",
        "franchise filter on. Each title was looked up by `show_id`.",
        "",
        f"- neighbours scored: **{considered}**",
        f"- share with cosine >= {ceiling:.2f}: **{sat_rate:.4f}**",
        f"- share that name a shared director or actor: **{people_rate:.4f}**",
        "",
        "A high saturation share means many lists are genre-token ties. The reason",
        "text now says so when no person is shared, including when the score is",
        "saturated. People-backed neighbours are the ones the director and cast",
        "weights actually earned. Cast is empty in this extract, so that share is",
        "almost entirely directors.",
        "",
        "## No history: free-text positions",
        "",
        "There is no user. These queries are the cold-start path",
        "(`recommend_from_text`). A refusal is the correct result when the",
        "vector is all zeros.",
        "",
        "| position | query | outcome | detail |",
        "| --- | --- | --- | --- |",
        *probe_rows,
        "",
        "## Fuzzy title positions",
        "",
        "A typo of a real title should resolve. A string that is not a title",
        "should return suggestions and not a recommendation.",
        "",
        "| typed | resolved | first result or suggestions |",
        "| --- | --- | --- |",
        *fuzzy_rows,
        "",
        "## How to improve this, given the file we have",
        "",
        "Saturation falls when the soup contains something other than genre:",
        "cast and a synopsis. Those columns are absent here, so turning the genre",
        "weight down is the only lever, and the ablation already shows genre weight",
        "1 lowers genre precision without creating a watch-label signal. Country",
        "weight stays 0 because the Pakistan labels are wrong. The next real",
        "improvement is a catalogue extract that has cast and description, then",
        "a re-run of this script and `scripts/evaluate.py`.",
        "",
    ]
    path = config.reports_dir / "reliability.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {path}")
    print(f"saturation>={ceiling:.2f} {sat_rate:.4f}  people-backed {people_rate:.4f}")


if __name__ == "__main__":
    main()
